// เนื้อหา "วันพิเศษกดได้" (ซินแสนุ้ย 2026-09-23): กดป้ายวันความรัก/วันลาภสวรรค์ → เด้งคำอธิษฐาน + ข้อมูลเทพ.
//   วันความรัก → เฒ่าจันทรา (เย่ว์เหล่า 月老) เทพด้ายแดง — คำอธิษฐาน + ศาลเจ้า/วัด (เนื้อหาจาก Google Docs ที่ซินแสให้)
//   วันลาภสวรรค์ → เทพเทียนไช้ (财神) — ทิศมงคลรายวัน + คำอธิษฐาน (ร่างตั้งต้น รอสลับเป็นของซินแสเมื่อได้มา)
// static ล้วน (ไม่มี AI). แต่ละอันมีปุ่ม "คำอธิษฐานเฉพาะคุณ" ที่ยิง /api/prayer (personalize ตาม 用神) เพิ่มได้.
export type BlessingShrine = { name: string; place: string }

export type SpecialDayBlessing = {
  /** จับจากชื่อดาว (s.name) */
  match: RegExp
  /** ไอคอน + สีหัว */
  emoji: string
  accent: string
  /** ชื่อเทพ (ไทย + จีน) */
  deity: string
  /** ความเป็นมา/ที่มาสั้น ๆ */
  intro: string
  /** บทอธิษฐานเฉพาะ (มี placeholder ให้แทนชื่อ/สถานที่) */
  prayer: string
  /** ศาลเจ้า/วัดที่มีเทพองค์นี้ (ความรัก) */
  shrines?: BlessingShrine[]
  /** true = โชว์ "ทิศมงคลวันนี้" (ลาภสวรรค์) จาก detail.luckyDirection */
  showDirection?: boolean
  /** topic สำหรับปุ่ม generator "คำอธิษฐานเฉพาะคุณ" (/api/prayer) */
  generatorTopic: 'love' | 'wealth'
  generatorLabel: string
}

